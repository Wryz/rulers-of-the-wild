/** A tool class's DS WeaponDef numbers (§5.2: the template synthWeapon starts from). */
const weaponRow = (damageMul: number, cut: number, cleave: number, bite: number, tempo: number, choke: number) => ({ damageMul, cut, cleave, bite, tempo, choke });

/** The six WeaponDef fields' metadata for one tool class. */
function weaponFields(source: string): Record<'damageMul' | 'cut' | 'cleave' | 'bite' | 'tempo' | 'choke', FieldMeta> {
  const m = (unit: string): FieldMeta => ({ unit, source });
  return { damageMul: m('× (DS WeaponDef)'), cut: m('DS WeaponDef'), cleave: m('DS WeaponDef'), bite: m('DS WeaponDef'), tempo: m('× (DS WeaponDef)'), choke: m('DS WeaponDef') };
}

