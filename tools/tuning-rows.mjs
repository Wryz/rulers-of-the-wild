// From the repo root, on Node 22: npx vite-node tools/tuning-rows.mjs [--write]
// Lists every registered tuning key (the sim's and the client's tables) that has no row in docs/M1-DESIGN.md §9.1, as
// rows (| TABLE | key | value | unit | source |) grouped by table, from the registry's own values and metadata. The
// coverage rule is the one packages/sim/tests/noBareConstants.test.ts and apps/client/tests/tuningDoc.test.ts check
// (P38, RR-7; packages/sim/tests/support/tuningDoc.ts). --write puts the rows into §9.1, under "Registered keys added
// at P38", just before §9.2.
import { readFileSync, writeFileSync } from 'node:fs';
import { TUNING, getTuningValue, tuningLeaves } from '../packages/sim/src/tuning/registry.ts';
import { uncoveredTuningKeys } from '../packages/sim/tests/support/tuningDoc.ts';
import '../packages/sim/src/index.ts';
import { CLIENT_TUNING_MODULES } from '../apps/client/tests/support/tuningModules.ts';

for (const m of CLIENT_TUNING_MODULES) await import(/* @vite-ignore */ new URL(`../apps/client/src/${m}.ts`, import.meta.url).pathname);

const docUrl = new URL('../docs/M1-DESIGN.md', import.meta.url);
const doc = readFileSync(docUrl, 'utf8');
const cell = (s) => String(s).replace(/\|/g, '\\|');
const fmt = (v) => (typeof v === 'number' ? String(v) : typeof v === 'string' ? `'${v}'` : JSON.stringify(v));
const out = [];
for (const e of TUNING) {
  const missing = uncoveredTuningKeys(doc, e.name, tuningLeaves(e).map((l) => l.key));
  if (missing.length === 0) continue;
  const leaves = new Map(tuningLeaves(e).map((l) => [l.key, l]));
  out.push(`##### ${e.name} (folder "${e.folder}")`, '', '| Table | Key | Value | Unit | Source |', '|---|---|---|---|---|');
  for (const k of missing) {
    const l = leaves.get(k);
    out.push(`| ${e.name} | ${k} | ${cell(fmt(getTuningValue(e.name, k)))} | ${cell(l.meta.unit)} | ${cell(l.meta.source)} |`);
  }
  out.push('');
}
if (!process.argv.includes('--write')) {
  console.log(out.length ? out.join('\n') : 'Every registered tuning key has a §9.1 row.');
} else if (out.length > 0) {
  const at = doc.indexOf('### 9.2 ');
  const head = '#### Registered keys added at P38';
  const intro =
    `${head}\n\nKeys the packages registered after the tables above were written (their values, units and sources are the ` +
    `registry's, generated by \`tools/tuning-rows.mjs\`; P38, RR-7). The P38 tests fail on a registered key with no ` +
    `§9.1 row, so code and this section can no longer drift apart silently.\n\n`;
  const has = doc.indexOf(head);
  const next = has >= 0 ? doc.slice(0, at) + out.join('\n') + '\n' + doc.slice(at) : doc.slice(0, at) + intro + out.join('\n') + '\n' + doc.slice(at);
  writeFileSync(docUrl, next);
  console.log(`wrote ${out.filter((l) => l.startsWith('| ') && !l.startsWith('| Table')).length} rows into §9.1`);
}
